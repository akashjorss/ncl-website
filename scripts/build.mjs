import fs from "node:fs/promises";
import path from "node:path";
import MarkdownIt from "markdown-it";
import texmath from "markdown-it-texmath";
import katex from "katex";

const root = path.resolve(import.meta.dirname, "..");
const origin = "https://neuralcontinuitylabs.com";
const escape = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
const md = new MarkdownIt({ html: true, linkify: true }).use(texmath, {
  engine: katex,
  delimiters: "dollars",
  katexOptions: {
    throwOnError: true,
    strict: "error",
    output: "htmlAndMathml",
  },
});
md.renderer.rules.table_open = () => '<div class="table-scroll"><table>\n';
md.renderer.rules.table_close = () => "</table></div>\n";
const notes = [];
for (const file of (await fs.readdir(path.join(root, "content/notes"))).filter(
  (f) => f.endsWith(".md"),
)) {
  const source = await fs.readFile(
    path.join(root, "content/notes", file),
    "utf8",
  );
  const match = source.match(/^---\n([\s\S]+?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`Missing frontmatter in ${file}`);
  const meta = Object.fromEntries(
    match[1]
      .split("\n")
      .filter(Boolean)
      .map((line) => {
        const index = line.indexOf(":");
        if (index < 1) throw new Error(`Invalid metadata in ${file}`);
        return [
          line.slice(0, index).trim(),
          line
            .slice(index + 1)
            .trim()
            .replace(/^(["'])(.*)\1$/, "$2"),
        ];
      }),
  );
  for (const key of ["title", "date", "description", "slug"])
    if (!meta[key]) throw new Error(`Missing ${key} in ${file}`);
  if (
    !/^\d{4}-\d{2}-\d{2}$/.test(meta.date) ||
    !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(meta.slug)
  )
    throw new Error(`Invalid date or slug in ${file}`);
  if (notes.some((n) => n.slug === meta.slug))
    throw new Error(`Duplicate slug ${meta.slug}`);
  notes.push({
    ...meta,
    html: md.render(match[2]),
    hasMath: /\$/.test(match[2]),
  });
}
notes.sort(
  (a, b) => b.date.localeCompare(a.date) || b.slug.localeCompare(a.slug),
);
const date = (d) =>
  new Date(d + "T12:00:00Z").toLocaleDateString("en-GB", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
function noteList(items) {
  return (
    '<ol class="note-list">' +
    items
      .map(
        (note) =>
          `<li class="note-row"><a href="/notes/${note.slug}/"><div lang="en"><h3>${escape(note.title)}</h3><p>${escape(note.description)}</p></div><span class="arrow" aria-hidden="true">↗</span></a></li>`,
      )
      .join("") +
    "</ol>"
  );
}
